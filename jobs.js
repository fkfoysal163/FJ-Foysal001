// Render Jobs By Category Page Function
function renderCategoryPage() {
    const container = document.getElementById('category-jobs-container');
    if (!container) return;

    const categorySlug = getQueryParam('category');
    const matchedCategory = categoryMasterMap.find(c => c.slug === categorySlug);
    
    const categoryHeading = document.getElementById('category-heading');
    const categoryBadge = document.getElementById('category-count-badge');
    const categoryBreadcrumb = document.getElementById('category-breadcrumb');
    const pageTitle = document.getElementById('category-page-title');

    const categoryTitleText = matchedCategory ? matchedCategory.name : "সকল ক্যাটাগরি";

    if (categoryHeading) categoryHeading.innerText = `${categoryTitleText} নিয়োগ বিজ্ঞপ্তি`;
    if (categoryBreadcrumb) categoryBreadcrumb.innerText = categoryTitleText;
    if (pageTitle) document.title = `${categoryTitleText} | চাকরির খবর`;

    // Filter Jobs by Category
    const filteredJobs = categorySlug 
        ? jobsData.filter(job => job.category.toLowerCase() === categorySlug.toLowerCase())
        : jobsData;

    if (categoryBadge) {
        categoryBadge.innerText = `${convertToBengaliNumber(filteredJobs.length)} টি চাকরি`;
    }

    if (filteredJobs.length > 0) {
        container.innerHTML = filteredJobs.map(createStandardCardHTML).join('');
    } else {
        container.innerHTML = `
            <div class="alert alert-info text-center py-4 w-100">
                <i class="fa-solid fa-folder-open fa-2x mb-2 text-secondary"></i>
                <h5 class="fw-bold">এই ক্যাটাগরিতে বর্তমানে কোনো চাকরির খবর নেই।</h5>
                <p class="mb-0 text-muted">অনুগ্রহ করে পরবর্তীতে আবার চেষ্টা করুন অথবা অন্যান্য ক্যাটাগরি ব্রাউজ করুন।</p>
            </div>
        `;
    }
}

// Render Sidebar Category List with Counts
function renderCategorySidebarWidget() {
    const widgetList = document.getElementById('category-widget-list');
    if (!widgetList) return;

    const currentCategorySlug = getQueryParam('category');

    const listHTML = categoryMasterMap.map(cat => {
        const count = jobsData.filter(j => j.category === cat.slug).length;
        const isActive = currentCategorySlug === cat.slug ? 'active fw-bold' : '';

        return `
            <a href="category.html?category=${cat.slug}" class="list-group-item list-group-item-action d-flex justify-content-between align-items-center ${isActive}">
                <span><i class="fa-solid fa-chevron-right text-primary me-2 fs-7"></i>${cat.name}</span>
                <span class="badge bg-secondary rounded-pill">${convertToBengaliNumber(count)}</span>
            </a>
        `;
    }).join('');

    widgetList.innerHTML = listHTML;
}

