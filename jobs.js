function formatBengaliDate(dateString) {
    if (!dateString) return '';
    const months = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'];
    const numbers = { '0': '০', '1': '১', '2': '২', '3': '৩', '4': '৪', '5': '৫', '6': '৬', '7': '৭', '8': '৮', '9': '৯' };

    const dateObj = new Date(dateString);
    const day = String(dateObj.getDate()).padStart(2, '0');
    const monthIndex = dateObj.getMonth();
    const year = dateObj.getFullYear();

    const bnDay = day.split('').map(char => numbers[char] || char).join('');
    const bnYear = String(year).split('').map(char => numbers[char] || char).join('');

    return `${bnDay} ${months[monthIndex]}, ${bnYear}`;
}

function convertToBengaliNumber(num) {
    const numbers = { '0': '০', '1': '১', '2': '২', '3': '৩', '4': '৪', '5': '৫', '6': '৬', '7': '৭', '8': '৮', '9': '৯' };
    return String(num).split('').map(char => numbers[char] || char).join('');
}

