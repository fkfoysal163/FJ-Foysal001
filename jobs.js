function renderRelatedJobs(currentJob) {
    const relatedListContainer = document.getElementById('related-jobs-list');
    if (!relatedListContainer) return;

    const relatedJobs = jobsData.filter(j => j.category === currentJob.category && j.id !== currentJob.id).slice(0, 2);

    if (relatedJobs.length > 0) {
        relatedListContainer.innerHTML = relatedJobs.map(createStandardCardHTML).join('');
    } else {
        const fallbackJobs = jobsData.filter(j => j.id !== currentJob.id).slice(0, 2);
        relatedListContainer.innerHTML = fallbackJobs.map(createStandardCardHTML).join('');
    }
}

